/**
 * GitHub API клиент для интеграции
 */

interface GitHubPR {
  title: string;
  body: string;
  head: string;
  base: string;
}

interface GitHubIssue {
  title: string;
  body: string;
  labels?: string[];
}

interface GitHubComment {
  body: string;
}

export class GitHubClient {
  private token: string;
  private owner: string;
  private repo: string;
  private baseUrl = 'https://api.github.com';

  constructor(token: string, owner: string, repo: string) {
    this.token = token;
    this.owner = owner;
    this.repo = repo;
  }

  private async request<T>(endpoint: string, options: RequestInit = {}): Promise<T> {
    const url = `${this.baseUrl}/repos/${this.owner}/${this.repo}${endpoint}`;
    
    const response = await fetch(url, {
      ...options,
      headers: {
        'Authorization': `Bearer ${this.token}`,
        'Accept': 'application/vnd.github.v3+json',
        'Content-Type': 'application/json',
        ...options.headers,
      },
    });

    if (!response.ok) {
      throw new Error(`GitHub API error: ${response.status} ${response.statusText}`);
    }

    return response.json();
  }

  // Получение списка PR
  async listPRs(state: 'open' | 'closed' | 'all' = 'open') {
    return this.request<any[]>(`/pulls?state=${state}`);
  }

  // Получение конкретного PR
  async getPR(prNumber: number) {
    return this.request<any>(`/pulls/${prNumber}`);
  }

  // Создание PR
  async createPR(pr: GitHubPR) {
    return this.request<any>('/pulls', {
      method: 'POST',
      body: JSON.stringify(pr),
    });
  }

  // Анализ кода в PR с помощью ИИ
  async analyzeCode(prNumber: number, aiAnalysis: string) {
    const comment: GitHubComment = {
      body: `🤖 **AI Code Review**\n\n${aiAnalysis}\n\n---\n*Generated by Hephaestus AI*`,
    };

    return this.request<any>(`/issues/${prNumber}/comments`, {
      method: 'POST',
      body: JSON.stringify(comment),
    });
  }

  // Получение файлов в PR
  async getPRFiles(prNumber: number) {
    return this.request<any[]>(`/pulls/${prNumber}/files`);
  }

  // Получение списка issues
  async listIssues(state: 'open' | 'closed' | 'all' = 'open') {
    return this.request<any[]>(`/issues?state=${state}`);
  }

  // Создание issue
  async createIssue(issue: GitHubIssue) {
    return this.request<any>('/issues', {
      method: 'POST',
      body: JSON.stringify(issue),
    });
  }

  // Добавление комментария к issue
  async addIssueComment(issueNumber: number, comment: GitHubComment) {
    return this.request<any>(`/issues/${issueNumber}/comments`, {
      method: 'POST',
      body: JSON.stringify(comment),
    });
  }

  // Автоматическая категоризация issue
  async triageIssue(issueNumber: number, category: string) {
    const labels = this.getLabelsForCategory(category);
    
    await this.request<any>(`/issues/${issueNumber}`, {
      method: 'PATCH',
      body: JSON.stringify({ labels }),
    });

    const comment: GitHubComment = {
      body: `🤖 Issue automatically categorized as **${category}** by Hephaestus AI`,
    };

    await this.addIssueComment(issueNumber, comment);
  }

  // Получение меток для категории
  private getLabelsForCategory(category: string): string[] {
    const labelMap: Record<string, string[]> = {
      bug: ['bug', 'needs-triage'],
      feature: ['enhancement', 'feature'],
      documentation: ['documentation'],
      performance: ['performance'],
      security: ['security'],
    };

    return labelMap[category] || ['triage'];
  }

  // Проверка доступа к репозиторию
  async checkAccess() {
    try {
      const repo = await this.request<any>('');
      return { 
        success: true, 
        name: repo.name,
        permissions: repo.permissions 
      };
    } catch (error) {
      return { 
        success: false, 
        error: error instanceof Error ? error.message : 'Unknown error' 
      };
    }
  }
}